"use client";

import { useEffect, useId, useRef, useState } from "react";
import { Button } from "@/components/ui/Button";
import { Notice } from "@/components/ui/Notice";
import { Panel } from "@/components/ui/Panel";
import type { AuthClient } from "@/lib/auth";

const WRONG_CODE = "El código no es correcto. Comprueba la hora de tu dispositivo e inténtalo de nuevo.";
const SETUP_FAILED = "No se pudo preparar el doble factor. Recarga la página e inténtalo de nuevo.";
const VERIFY_FAILED = "No se pudo completar la verificación. Inténtalo de nuevo.";

type Phase =
  | { kind: "loading" }
  | { kind: "failed" }
  | { kind: "enroll"; factorId: string; qr: string; secret: string }
  | { kind: "verify"; factorId: string };

export type MfaPanelProps = {
  client: AuthClient;
  /** Called once the code is accepted and the session reached `aal2`. */
  onVerified: () => void;
};

export function MfaPanel({ client, onVerified }: MfaPanelProps) {
  const [phase, setPhase] = useState<Phase>({ kind: "loading" });
  const [code, setCode] = useState("");
  const [error, setError] = useState<"wrong" | "other" | null>(null);
  const [pending, setPending] = useState(false);
  const inputRef = useRef<HTMLInputElement>(null);
  const startedRef = useRef(false);
  const submittingRef = useRef(false);
  const errorId = useId();
  const ready = phase.kind === "enroll" || phase.kind === "verify";

  useEffect(() => {
    // Strict Mode runs effects twice in development; enrolling twice would create two factors.
    if (startedRef.current) return;
    startedRef.current = true;
    (async () => {
      try {
        const { data, error: listError } = await client.auth.mfa.listFactors();
        if (listError || !data) throw listError ?? new Error("no factors");
        const verified = data.totp?.find((factor) => factor.status === "verified");
        if (verified) {
          setPhase({ kind: "verify", factorId: verified.id });
          return;
        }
        const { data: enrolled, error: enrollError } = await client.auth.mfa.enroll({ factorType: "totp" });
        if (enrollError || !enrolled) throw enrollError ?? new Error("no enrolment");
        setPhase({ kind: "enroll", factorId: enrolled.id, qr: enrolled.totp.qr_code, secret: enrolled.totp.secret });
      } catch {
        setPhase({ kind: "failed" });
      }
    })();
  }, [client]);

  useEffect(() => {
    if (ready) inputRef.current?.focus();
  }, [ready]);

  async function submit(event: React.FormEvent) {
    event.preventDefault();
    if (!ready || code.length !== 6 || submittingRef.current) return;
    submittingRef.current = true;
    setPending(true);
    setError(null);
    try {
      const { data: challenge, error: challengeError } = await client.auth.mfa.challenge({ factorId: phase.factorId });
      if (challengeError || !challenge) throw challengeError ?? new Error("no challenge");
      const { error: verifyError } = await client.auth.mfa.verify({ factorId: phase.factorId, challengeId: challenge.id, code });
      if (verifyError) {
        setError(verifyError.code === "mfa_verification_failed" ? "wrong" : "other");
        if (verifyError.code === "mfa_verification_failed") setCode("");
        inputRef.current?.focus();
        return;
      }
      onVerified();
    } catch {
      setError("other");
    } finally {
      submittingRef.current = false;
      setPending(false);
    }
  }

  return (
    <div className="mx-auto flex w-full max-w-md flex-col gap-5 py-16">
      <h1 className="text-xl font-semibold">Verificación en dos pasos</h1>
      {phase.kind === "loading" ? <Notice>Cargando…</Notice> : null}
      {phase.kind === "failed" ? <Notice tone="bad">{SETUP_FAILED}</Notice> : null}
      {ready ? (
        <Panel
          title={phase.kind === "enroll" ? "Activa el doble factor" : "Introduce tu código"}
          description={
            phase.kind === "enroll"
              ? "Escanea el código QR con una aplicación de autenticación (Google Authenticator, 1Password, Authy…) y escribe el código que muestra."
              : "Abre tu aplicación de autenticación y escribe el código actual."
          }
        >
          <form onSubmit={submit} className="flex flex-col gap-4">
            {phase.kind === "enroll" ? (
              <div className="flex flex-col items-start gap-3">
                {/* eslint-disable-next-line @next/next/no-img-element -- data URI generated by Supabase, nothing to optimise */}
                <img src={phase.qr} alt="Código QR para configurar la aplicación de autenticación" width={176} height={176} className="rounded-base border border-hair bg-surface" />
                <div className="flex flex-col gap-1">
                  <p className="text-xs text-muted">Clave secreta</p>
                  <code className="break-all text-s text-ink">{phase.secret}</code>
                </div>
              </div>
            ) : null}
            <div className="flex flex-col gap-1.5">
              <label htmlFor={`${errorId}-code`} className="text-s font-medium">
                Código de 6 dígitos
              </label>
              <input
                ref={inputRef}
                id={`${errorId}-code`}
                type="text"
                inputMode="numeric"
                autoComplete="one-time-code"
                maxLength={6}
                value={code}
                onChange={(event) => {
                  setCode(event.target.value.replace(/\D/g, "").slice(0, 6));
                  setError(null);
                }}
                aria-invalid={error === "wrong" ? true : undefined}
                aria-describedby={error ? errorId : undefined}
                className="w-40 rounded-base border border-hair bg-surface px-3 py-2 text-m tracking-widest text-ink"
              />
            </div>
            {error ? (
              <Notice tone="bad" id={errorId}>
                {error === "wrong" ? WRONG_CODE : VERIFY_FAILED}
              </Notice>
            ) : null}
            <Button type="submit" variant="primary" disabled={code.length !== 6 || pending} aria-busy={pending} className="justify-center">
              {phase.kind === "enroll" ? "Activar doble factor" : "Verificar código"}
            </Button>
          </form>
        </Panel>
      ) : null}
    </div>
  );
}
